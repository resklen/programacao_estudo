"""
Faça um programa que receba três números, calcule e mostre a multiplicação
desses números.

"""
primeiro_numero = float(input('Insira o primeiro número: '))
segundo_numero = float(input('Insira o segundo número: '))
terceiro_numero = float(input('Insira o terceiro número: '))

multiplicacao = primeiro_numero * segundo_numero * terceiro_numero

print(f'A multiplicação desses números é: {multiplicacao}')
