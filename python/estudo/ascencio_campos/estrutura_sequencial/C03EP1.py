"""
Faça um programa que receba dois números, calcule e mostre a subtração
do primeiro número pelo segundo.

"""
primeiro_numero = float(input('Insira o primeiro número: '))
segundo_numero = float(input('Insira o segundo número: '))

subtracao = primeiro_numero - segundo_numero

print(f'O resultado da subtração do primeiro número pelo segundo número é {subtracao}')
