"""
Faça um programa que calcule e mostre a tabuada de um número digitado
pelo usuário.

"""

numero = int(input('Insira um número para saber sua tabuada: '))

um = numero * 1
dois = numero * 2
tres = numero * 3
quatro = numero * 4
cinco = numero * 5
seis = numero * 6
sete = numero * 7
oito = numero * 8
nove = numero * 9
dez = numero * 10

print(f'{numero} X 1 = {um}')
print(f'{numero} X 2 = {dois}')
print(f'{numero} X 3 = {tres}')
print(f'{numero} X 4 = {quatro}')
print(f'{numero} X 5 = {cinco}')
print(f'{numero} X 6 = {seis}')
print(f'{numero} X 7 = {sete}')
print(f'{numero} X 8 = {oito}')
print(f'{numero} X 9 = {nove}')
print(f'{numero} X 10 = {dez}')
